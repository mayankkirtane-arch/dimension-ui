import { PageSchema, BlockInstance } from "./types";

/**
 * Escapes strings for safe inclusion in JSX literals.
 */
function escapeJsx(str: string = ""): string {
  return str
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
}

/**
 * Generates production-ready Next.js 15 / React 19 TSX code from a PageSchema.
 */
export function generatePageCode(page: PageSchema): string {
  const { title, tokens, blocks } = page;

  const fontClass =
    tokens.fontFamily === "Outfit"
      ? "font-sans"
      : tokens.fontFamily === "Plus Jakarta Sans"
      ? "font-sans"
      : "font-sans";

  const radiusMap: Record<string, string> = {
    none: "rounded-none",
    sm: "rounded-sm",
    md: "rounded-md",
    lg: "rounded-xl",
    xl: "rounded-2xl",
    full: "rounded-3xl",
  };
  const roundedClass = radiusMap[tokens.borderRadius] || "rounded-xl";

  const blocksJsx = blocks
    .map((block, idx) => renderBlockCode(block, idx, roundedClass, tokens))
    .join("\n\n");

  return `"use client";

import React from "react";
import { motion } from "framer-motion";
import {
  ArrowRight,
  Sparkles,
  Zap,
  Shield,
  Layers,
  Cpu,
  Palette,
  Terminal,
  CheckCircle2,
} from "lucide-react";

/**
 * Page: ${escapeJsx(title)}
 * Generated by DimensionUI Page Builder
 * Date: ${new Date().toISOString()}
 */
export default function GeneratedPage() {
  return (
    <div
      className="min-h-screen text-slate-100 ${fontClass} selection:bg-purple-500/30 selection:text-white"
      style={{
        backgroundColor: "${tokens.bgCanvas}",
        color: "${tokens.textColor}",
      }}
    >
${blocksJsx}
    </div>
  );
}
`;
}

function renderBlockCode(
  block: BlockInstance,
  index: number,
  roundedClass: string,
  tokens: PageSchema["tokens"]
): string {
  switch (block.type) {
    case "hero":
      return renderHeroCode(block.props, roundedClass, tokens);
    case "features":
      return renderFeaturesCode(block.props, roundedClass, tokens);
    case "cta":
      return renderCtaCode(block.props, roundedClass, tokens);
    case "footer":
      return renderFooterCode(block.props, roundedClass, tokens);
    default:
      return `      {/* Unknown block type: ${block.type} */}`;
  }
}

function renderHeroCode(props: any, roundedClass: string, tokens: any): string {
  const alignClass = props.align === "left" ? "text-left items-start" : "text-center items-center";

  return `      {/* Hero Section */}
      <section className="relative overflow-hidden py-24 sm:py-32 px-4 sm:px-6 lg:px-8 border-b border-white/[0.06]">
        <div className="absolute inset-0 pointer-events-none opacity-40">
          <div
            className="absolute top-1/4 left-1/2 -translate-x-1/2 -translate-y-1/2 w-[600px] h-[350px] blur-[120px] rounded-full"
            style={{
              background: "radial-gradient(circle, ${tokens.primaryAccent}44 0%, transparent 70%)",
            }}
          />
        </div>

        <div className="relative max-w-5xl mx-auto flex flex-col ${alignClass}">
          {/* Badge */}
          <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-full border border-white/10 bg-white/[0.04] backdrop-blur-md mb-6 shadow-sm">
            <Sparkles className="w-3.5 h-3.5 text-cyan-400" />
            <span className="text-xs font-medium tracking-wide text-slate-300">
              "${escapeJsx(props.badge)}"
            </span>
          </div>

          {/* Headline */}
          <h1 className="text-4xl sm:text-6xl lg:text-7xl font-extrabold tracking-tight leading-[1.1] max-w-4xl mb-6">
            ${escapeJsx(props.headline)}{" "}
            <span
              className="bg-clip-text text-transparent"
              style={{
                backgroundImage: "linear-gradient(135deg, ${tokens.primaryAccent}, ${tokens.secondaryAccent})",
              }}
            >
              ${escapeJsx(props.highlightText)}
            </span>
          </h1>

          {/* Description */}
          <p className="text-lg sm:text-xl text-slate-400 max-w-2xl mb-10 leading-relaxed">
            "${escapeJsx(props.description)}"
          </p>

          {/* CTA Buttons */}
          <div className="flex flex-wrap gap-4 items-center justify-center">
            <a
              href="${escapeJsx(props.primaryCtaLink)}"
              className="inline-flex items-center gap-2 px-6 py-3.5 ${roundedClass} font-semibold text-white shadow-lg transition-transform hover:-translate-y-0.5 active:translate-y-0"
              style={{
                backgroundColor: "${tokens.primaryAccent}",
                boxShadow: "0 10px 25px -5px ${tokens.primaryAccent}66",
              }}
            >
              ${escapeJsx(props.primaryCtaText)}
              <ArrowRight className="w-4 h-4" />
            </a>

            <a
              href="${escapeJsx(props.secondaryCtaLink)}"
              className="inline-flex items-center gap-2 px-6 py-3.5 ${roundedClass} font-semibold text-slate-300 border border-white/10 bg-white/[0.03] hover:bg-white/[0.08] transition-colors"
            >
              ${escapeJsx(props.secondaryCtaText)}
            </a>
          </div>

          ${
            props.showMockup
              ? `{/* Preview Mockup Card */}
          <div className="mt-16 w-full ${roundedClass} border border-white/10 bg-white/[0.02] p-4 sm:p-6 backdrop-blur-xl shadow-2xl">
            <div className="h-64 sm:h-96 ${roundedClass} border border-white/[0.08] bg-[#0c0d18] flex items-center justify-center relative overflow-hidden">
              <div className="absolute inset-0 bg-gradient-to-tr from-purple-500/10 via-transparent to-cyan-500/10" />
              <div className="relative text-center p-6">
                <div className="inline-block p-4 rounded-2xl bg-white/[0.04] border border-white/10 mb-4">
                  <Cpu className="w-8 h-8 text-cyan-400" />
                </div>
                <h3 className="text-lg font-semibold text-white mb-1">Interactive Component Preview</h3>
                <p className="text-xs text-slate-400">High-performance canvas rendered with GPU physics.</p>
              </div>
            </div>
          </div>`
              : ""
          }
        </div>
      </section>`;
}

function renderFeaturesCode(props: any, roundedClass: string, tokens: any): string {
  const colClass =
    props.columns === "2"
      ? "sm:grid-cols-2"
      : props.columns === "4"
      ? "sm:grid-cols-2 lg:grid-cols-4"
      : "sm:grid-cols-2 lg:grid-cols-3";

  const items = Array.isArray(props.features) ? props.features : [];

  return `      {/* Features Grid */}
      <section className="py-24 px-4 sm:px-6 lg:px-8 max-w-7xl mx-auto border-b border-white/[0.06]">
        <div className="text-center max-w-3xl mx-auto mb-16">
          <span className="text-xs font-bold tracking-widest uppercase text-cyan-400 mb-3 block">
            ${escapeJsx(props.eyebrow)}
          </span>
          <h2 className="text-3xl sm:text-5xl font-extrabold tracking-tight mb-4 text-white">
            ${escapeJsx(props.headline)}
          </h2>
          <p className="text-base sm:text-lg text-slate-400">
            ${escapeJsx(props.description)}
          </p>
        </div>

        <div className="grid grid-cols-1 ${colClass} gap-6">
          ${items
            .map(
              (item: any) => `
          <div className="${roundedClass} border border-white/[0.08] bg-[#0e0e1a]/80 p-6 sm:p-8 backdrop-blur-sm transition-all duration-300 hover:border-white/20 hover:-translate-y-1">
            <div className="w-12 h-12 rounded-xl bg-purple-500/10 border border-purple-500/20 flex items-center justify-center mb-5 text-purple-400">
              <Zap className="w-6 h-6" />
            </div>
            <h3 className="text-xl font-bold text-white mb-2">${escapeJsx(item.title)}</h3>
            <p className="text-sm text-slate-400 leading-relaxed">${escapeJsx(item.description)}</p>
          </div>`
            )
            .join("")}
        </div>
      </section>`;
}

function renderCtaCode(props: any, roundedClass: string, tokens: any): string {
  const isSplit = props.layout === "split";

  return `      {/* Call to Action */}
      <section className="py-24 px-4 sm:px-6 lg:px-8 max-w-6xl mx-auto">
        <div
          className="relative overflow-hidden ${roundedClass} border border-white/10 p-8 sm:p-14 text-center ${
    isSplit ? "lg:text-left lg:flex lg:items-center lg:justify-between" : ""
  }"
          style={{
            backgroundColor: "${tokens.bgSurface}",
            boxShadow: "0 25px 50px -12px rgba(0,0,0,0.5)",
          }}
        >
          <div className="absolute top-0 right-0 -translate-y-1/2 translate-x-1/3 w-96 h-96 blur-[100px] pointer-events-none rounded-full bg-purple-500/20" />

          <div className="${isSplit ? "max-w-xl" : "max-w-2xl mx-auto"} relative z-10">
            <span className="text-xs font-bold tracking-widest uppercase text-cyan-400 mb-2 block">
              ${escapeJsx(props.eyebrow)}
            </span>
            <h2 className="text-3xl sm:text-4xl font-extrabold text-white tracking-tight mb-4">
              ${escapeJsx(props.headline)}
            </h2>
            <p className="text-base text-slate-400 mb-6 leading-relaxed">
              ${escapeJsx(props.description)}
            </p>
            <p className="text-xs text-slate-500 font-medium">
              ${escapeJsx(props.secondaryText)}
            </p>
          </div>

          <div className="mt-8 ${isSplit ? "lg:mt-0" : ""} relative z-10 flex-shrink-0">
            <a
              href="${escapeJsx(props.buttonLink)}"
              className="inline-flex items-center gap-2 px-8 py-4 ${roundedClass} font-bold text-white shadow-xl transition-transform hover:scale-[1.02] active:scale-[0.98]"
              style={{
                backgroundColor: "${tokens.primaryAccent}",
                boxShadow: "0 10px 25px -5px ${tokens.primaryAccent}66",
              }}
            >
              ${escapeJsx(props.buttonText)}
              <ArrowRight className="w-5 h-5" />
            </a>
          </div>
        </div>
      </section>`;
}

function renderFooterCode(props: any, roundedClass: string, tokens: any): string {
  const columns = Array.isArray(props.columns) ? props.columns : [];

  return `      {/* Footer */}
      <footer className="border-t border-white/[0.06] bg-[#07070d] py-16 px-4 sm:px-6 lg:px-8">
        <div className="max-w-7xl mx-auto grid grid-cols-1 md:grid-cols-4 gap-10 mb-12">
          <div className="md:col-span-1">
            <div className="flex items-center gap-2 font-bold text-xl text-white mb-3">
              <Sparkles className="w-5 h-5 text-purple-400" />
              <span>${escapeJsx(props.brandName)}</span>
            </div>
            <p className="text-xs text-slate-400 leading-relaxed max-w-xs">
              ${escapeJsx(props.tagline)}
            </p>
          </div>

          <div className="md:col-span-3 grid grid-cols-2 sm:grid-cols-3 gap-8">
            ${columns
              .map(
                (col: any) => `
            <div>
              <h4 className="text-xs font-bold uppercase tracking-wider text-slate-300 mb-4">${escapeJsx(
                col.title
              )}</h4>
              <ul className="space-y-2.5 text-xs text-slate-400">
                ${(col.links || [])
                  .map(
                    (link: any) => `
                <li>
                  <a href="${escapeJsx(link.href)}" className="hover:text-white transition-colors">
                    ${escapeJsx(link.label)}
                  </a>
                </li>`
                  )
                  .join("")}
              </ul>
            </div>`
              )
              .join("")}
          </div>
        </div>

        <div className="max-w-7xl mx-auto pt-8 border-t border-white/[0.06] flex flex-col sm:flex-row items-center justify-between text-xs text-slate-500 gap-4">
          <p>${escapeJsx(props.copyrightText)}</p>
          <p>Powered by DimensionUI</p>
        </div>
      </footer>`;
}

/**
 * Returns formatted JSON schema for a page.
 */
export function generatePageJson(page: PageSchema): string {
  return JSON.stringify(page, null, 2);
}
